"""Write ``docs/REFERENCES_VERIFIED.md``: every bibliography entry with a DOI/arXiv link, its status (peer reviewed or preprint) and how it was verified.

    python scripts/verify_refs.py            # (needs internet) writes out/refs_verification.json
    python scripts/make_reference_table.py

Entries the automatic check could not confirm (it matched a different Crossref record) are listed with the manual evidence used instead.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from scripts.verify_refs import parse_bib  # noqa: E402

MANUAL = {
    "rebecq2018esim": "PMLR volume 87 page (proceedings.mlr.press/v87/rebecq18a.html) read directly: title, authors, 2nd Conference on Robot Learning, pp. 969-982, 2018 (Crossref returns only a 2020 reprint record).",
    "holm1979": "Scandinavian Journal of Statistics 6(2):65-70 (1979), JSTOR 4615733, confirmed in several independent reference lists (no Crossref DOI record found).",
    "yu2019physnet": "arXiv:1905.02419 record read: authors Yu, Li, Zhao; comment 'Accepted by BMVC2019'.",
}


def main() -> None:
    """Build the table."""
    entries = parse_bib((ROOT / "paper" / "refs.bib").read_text(encoding="utf-8"))
    ver = {r["key"]: r for r in json.loads((ROOT / "out" / "refs_verification.json").read_text(encoding="utf-8"))}
    lines = ["# Verified references", "", "Metadata was fetched from Crossref (DOI) or the arXiv API with `scripts/fetch_bib.py` and compared with `paper/refs.bib` by `scripts/verify_refs.py` "
             "(title similarity, year, volume, first page). Preprints are marked and are **not** peer reviewed unless a venue is stated.", "",
             "| key | reference | link | status | verification |", "|---|---|---|---|---|"]
    for e in entries:
        k = e["key"]
        title = re.sub(r"[{}\\]", "", e.get("title", ""))
        first = re.sub(r"[{}\\]", "", e.get("author", "").split(" and ")[0])
        year = e.get("year", "")
        venue = e.get("journal") or e.get("booktitle") or "arXiv"
        if e.get("doi"):
            link, status = f"[doi:{e['doi']}](https://doi.org/{e['doi']})", "peer reviewed"
        elif e.get("eprint"):
            link, status = f"[arXiv:{e['eprint']}](https://arxiv.org/abs/{e['eprint']})", "preprint" if "preprint" in e.get("note", "").lower() or "Preprint" in e.get("note", "") else "preprint (venue per note)"
        else:
            link, status = "(see note)", "peer reviewed"
        if k == "yu2019physnet":
            status = "peer reviewed (BMVC 2019, per arXiv comment)"
        if k == "holm1979":
            link = "[JSTOR 4615733](https://www.jstor.org/stable/4615733)"
        r = ver.get(k, {})
        how = "automatic (Crossref/arXiv match)" if r.get("ok") else MANUAL.get(k, "not verified")
        venue_clean = re.sub(r"[{}\\]", "", venue)
        lines.append(f"| `{k}` | {first.split(',')[0]} et al. ({year}). {title}. *{venue_clean}* | {link} | {status} | {how} |")
    n_auto = sum(1 for e in entries if ver.get(e["key"], {}).get("ok"))
    lines += ["", f"{n_auto} of {len(entries)} entries were confirmed automatically; the rest were confirmed manually as noted. Generated by `scripts/make_reference_table.py`."]
    out = ROOT / "docs" / "REFERENCES_VERIFIED.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out, f"({n_auto}/{len(entries)} automatic)")


if __name__ == "__main__":
    main()
